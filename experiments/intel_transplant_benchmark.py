"""Table I on REAL Intel Lab faults, via real-fault transplantation.

Why transplantation. The spatial-neighbour reference was measured to be unusable
for spread: neighbour imputation error 0.30 C against a within-window spread of
0.047 C (6.2-6.5x). So the clean counterpart cannot come from other sensors.

Transplantation keeps both things the evaluation needs:
  - the FAULTS are real: values and shapes are lifted from genuine low-voltage
    periods, never generated by a model of the defect;
  - the CLEAN counterpart is exact: it is the healthy segment before splicing,
    so the paper's metric err_E = |E_W(x') - E_W(x)| applies unchanged.

Two real fault families, separated by the voltage bands measured in
intel_explore.py:
  SAT    V < 2.3        sensor saturates (median 122.153 C, IQR 0). Real values
                        transplanted verbatim -- a real stuck-at-absurd fault.
  NOISE  2.3 <= V < 2.4 plausible-range readings with ~3x healthy IQR. Level-
                        matched on insertion (block median removed, local healthy
                        median added) so the transplanted quantity is the REAL
                        fault variability, which is what spread estimators see.

What is and is not real, stated plainly: fault values and within-block shape are
real; the timing and placement of blocks inside a healthy background are
synthetic. This is semi-synthetic, and weaker than an organically dirty series
with a known clean twin, which this dataset does not provide.
"""
import os
import sys
import pickle
import warnings
import numpy as np
import pandas as pd

warnings.filterwarnings('ignore', category=RuntimeWarning)
DQ = r"C:\Users\luckf\OneDrive\Desktop\dq-estimator-eval"
sys.path.insert(0, DQ)
sys.path.insert(0, os.path.join(DQ, 'experiments'))
from harness.harness1c import rolling_stats
from harness import phase2a_ext as p2x

W, SEG, RATE = 30, 2000, 0.05
SEEDS = [0, 1, 2, 3, 4]
MAX_CHUNKS = 160
MAX_BLOCK = 60
OUT = os.path.join(DQ, 'results', 'intel')


def contiguous_runs(sub, gap=10, min_len=3):
    out = []
    for m, g in sub.groupby('moteid'):
        v = g['temp'].to_numpy()
        e = g['epoch'].to_numpy()
        for seg in np.split(v, np.where(np.diff(e) > gap)[0] + 1):
            if len(seg) >= min_len:
                out.append(seg.astype(float))
    return out


def transplant(x, runs, rng, level_match):
    y = x.copy()
    n = len(x)
    budget = int(RATE * n)
    placed, tries = 0, 0
    while placed < budget and tries < 2000:
        tries += 1
        r = runs[rng.integers(len(runs))]
        L = int(min(len(r), budget - placed, MAX_BLOCK))
        if L < 2:
            continue
        s = rng.integers(0, len(r) - L + 1)
        blk = r[s:s + L].copy()
        pos = int(rng.integers(0, n - L))
        if level_match:
            blk = blk - np.median(blk) + np.median(x[max(0, pos - W):pos + W])
        y[pos:pos + L] = blk
        placed += L
    return y


def run_lengths(x):
    same = np.zeros(len(x), dtype=bool)
    same[1:] = (x[1:] == x[:-1])
    rid = np.cumsum(~same)
    return np.bincount(rid)[rid], same


def repair(x, thr):
    tl, same = run_lengths(x)
    y = x.astype(float).copy()
    y[(tl > thr) & same] = np.nan
    return y


def estimators(x):
    mean, med, std, madn = rolling_stats(x, W)
    _, _, _, iqr = p2x.rolling_extended(x, W)
    _, _, tc, _ = p2x.rolling_extended(x, W, trim_frac=0.10, consistency=True)
    return dict(mean=mean, median=med, std=std, madn=madn, iqr=iqr, trim_c=tc)


def mae(a, b):
    e = np.abs(a - b)
    e = e[np.isfinite(e)]
    return float(e.mean()) if e.size else np.nan


def gm(v):
    v = np.asarray(v, float)
    v = v[np.isfinite(v) & (v > 0)]
    return float(np.exp(np.mean(np.log(v)))) if v.size else np.nan


def main():
    os.makedirs(OUT, exist_ok=True)
    d = pickle.load(open(os.path.join(DQ, 'data', 'intel_lab', 'intel_parsed.pkl'), 'rb'))
    df = d['df'].sort_values(['moteid', 'epoch'])

    chunks = []
    for m, g in df[df.volt >= 2.5].groupby('moteid'):
        v = g['temp'].to_numpy().astype(float)
        for s in range(0, len(v) - SEG + 1, SEG):
            chunks.append((m, v[s:s + SEG]))
    rng0 = np.random.default_rng(12345)
    if len(chunks) > MAX_CHUNKS:
        keep = rng0.choice(len(chunks), MAX_CHUNKS, replace=False)
        chunks = [chunks[i] for i in sorted(keep)]

    sat = contiguous_runs(df[df.volt < 2.3])
    band = df[(df.volt >= 2.3) & (df.volt < 2.4)]
    noise = contiguous_runs(band[(band.temp > 0) & (band.temp < 50)])
    print(f"healthy chunks {len(chunks)} (len {SEG}); real fault runs: SAT {len(sat)}, "
          f"NOISE {len(noise)}  (median run length SAT {int(np.median([len(r) for r in sat]))}, "
          f"NOISE {int(np.median([len(r) for r in noise]))})")

    rows = []
    for ci, (m, x) in enumerate(chunks):
        thr = int(run_lengths(x[: int(0.2 * SEG)])[0].max())
        clean = estimators(x)
        clean_rep = estimators(repair(x, thr))
        for fam, runs, lm in (('SAT', sat, False), ('NOISE', noise, True)):
            for seed in SEEDS:
                rng = np.random.default_rng(seed * 1009 + ci)
                xb = transplant(x, runs, rng, lm)
                dirty = estimators(xb)
                dirty_rep = estimators(repair(xb, thr))
                e_std = mae(dirty['std'], clean['std'])
                e_mean = mae(dirty['mean'], clean['mean'])
                if not e_std or not e_mean:
                    continue
                r = dict(mote=m, chunk=ci, family=fam, seed=seed,
                         loc_median=mae(dirty['median'], clean['median']) / e_mean,
                         spr_madn=mae(dirty['madn'], clean['madn']) / e_std,
                         spr_iqr=mae(dirty['iqr'], clean['iqr']) / e_std,
                         spr_trim_c=mae(dirty['trim_c'], clean['trim_c']) / e_std,
                         spr_repair_std=mae(dirty_rep['std'], clean_rep['std']) / e_std)
                rows.append(r)
        if (ci + 1) % 40 == 0:
            print(f"  chunk {ci+1}/{len(chunks)}")

    res = pd.DataFrame(rows)
    res.to_csv(os.path.join(OUT, 'transplant_table1.csv'), index=False)
    cols = ['loc_median', 'spr_madn', 'spr_iqr', 'spr_trim_c', 'spr_repair_std']
    print("\n=== TABLE I ON REAL INTEL LAB FAULTS (ratio to naive; <1 = better) ===")
    print("    location ratio is median/mean; spread ratios are estimator/std\n")
    print(f"{'family':8s}" + ''.join(f"{c:>16s}" for c in cols))
    for fam in ('SAT', 'NOISE'):
        g = res[res.family == fam]
        print(f"{fam:8s}" + ''.join(f"{gm(g[c]):16.3f}" for c in cols))
        print(f"{'  %<1':8s}" + ''.join(f"{100*(g[c] < 1).mean():15.1f}%" for c in cols))
    print(f"\nn = {len(res)} (chunk x family x seed) cells")


if __name__ == '__main__':
    main()
